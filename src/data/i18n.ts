/**
 * Detects language with Hindi ('hi') as the default language for Indian users.
 */
export function detectInitialLang(urlLang?: string | null): LangCode {
  if (urlLang && urlLang in UI) {
    return urlLang as LangCode;
  }
  try {
    const saved = localStorage.getItem('wx_lang');
    if (saved && saved in UI) {
      return saved as LangCode;
    }
  } catch {
    // ignore storage errors
  }
  return 'hi';
}

export function formatTemplate(str: string, year: number, name?: string): string {
  return String(str)
    .replace(/\{Y\}/g, String(year))
    .replace(/\{n\}/g, name || '');
}
